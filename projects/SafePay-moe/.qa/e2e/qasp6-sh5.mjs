log('personal before', await bal());
await go(p, W+'/topup');
await keys('99999'); await sleep(800);
log('topup 99999:', (await txt(p)).split('\n').slice(0,6).join(' | '), 'btn disabled', await p.getByRole('button',{name:'טעינה'}).isDisabled());
