import {admin,SS,outline} from './h.mjs';
const A=await admin(); const p=A.p;
await p.goto('https://magnet-admin.vercel.app/reports',{waitUntil:'domcontentloaded'});
const card=p.locator('article').filter({hasText:'QA-AUTO פוסט לדיווח'});
await card.waitFor({timeout:20000});
await card.getByRole('button',{name:'טופל'}).click();
const dlg=p.locator('[role=dialog],dialog[open]').first();
await dlg.waitFor({timeout:10000});
console.log('DIALOG:',(await dlg.innerText()));
await dlg.locator('textarea').fill('QA-AUTO הערה');
await outline(p,dlg,'06e5ab-J2-resolve-dialog-note-desktop.png');
const t0=Date.now();
const resp=p.waitForResponse(r=>r.request().method()==='POST',{timeout:15000});
await dlg.getByRole('button').filter({hasText:/טופל|אישור|סגירה|שמירה/}).last().click();
const r=await resp; console.log('POST',r.status(),r.url(),r.request().headers()['next-action'], (await r.text()).slice(0,300));
await card.waitFor({state:'detached',timeout:10000}).then(()=>console.log('card gone ms',Date.now()-t0)).catch(()=>console.log('card still there'));
await p.screenshot({path:SS+'06e5ab-J2-after-open-desktop.png'});
console.log('tabs:',(await p.getByRole('tablist').first().innerText()).replace(/\n/g,' '));
await p.goto('https://magnet-admin.vercel.app/reports?status=resolved',{waitUntil:'domcontentloaded'});
const rc=p.locator('article').filter({hasText:'QA-AUTO פוסט לדיווח'});
await rc.waitFor({timeout:15000}).catch(()=>console.log('not in resolved'));
console.log('RESOLVED:',(await p.locator('main').innerText()).slice(0,1500));
await outline(p,rc,'06e5ab-J2-in-resolved-desktop.png',true);
console.log(JSON.stringify(A.net));
await A.close();
