import {admin,SS,outline} from './h.mjs';
const [st,note,tag]=[process.argv[2],process.argv[3],process.argv[4]];
const A=await admin(); const p=A.p; const posts=[];
p.on('request',q=>{if(q.method()==='POST') posts.push(q.postData()?.slice(0,300))});
await p.goto('https://magnet-admin.vercel.app/matchmaker',{waitUntil:'domcontentloaded'});
let row=p.locator('tr').filter({hasText:'דניאל'}); await row.waitFor({timeout:20000});
await row.getByRole('radio',{name:st}).click();
await row.getByLabel('הערה פנימית').fill(note);
const save=row.getByRole('button',{name:'שמירה'});
console.log('save enabled',await save.isEnabled());
await outline(p,row,`59bef2-${tag}-before-save-desktop.png`);
const resp=p.waitForResponse(r=>r.request().method()==='POST',{timeout:15000});
await save.click(); const r=await resp; console.log('POST',r.status(),posts.at(-1));
await save.isDisabled().then(v=>console.log('save disabled after',v));
await p.reload({waitUntil:'domcontentloaded'});
row=p.locator('tr').filter({hasText:'דניאל'}); await row.waitFor({timeout:20000});
console.log('AFTER RELOAD checked:',await row.locator('[role=radio][aria-checked=true]').innerText(),'| note:',JSON.stringify(await row.getByLabel('הערה פנימית').inputValue()));
console.log('tabs',(await p.locator('main').innerText()).slice(0,120).replace(/\n+/g,' '));
await outline(p,row,`59bef2-${tag}-after-reload-desktop.png`,true);
console.log(JSON.stringify(A.net.filter(x=>x.m==='POST'||x.s>=400||x.console)));
await A.close();
